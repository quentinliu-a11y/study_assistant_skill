"""Regenerate the files that are derived from one source, or check that they are current.

- The Chinese skill's scripts are a copy of the English skill's scripts.
- Each starter prompt is assembled from its skill's core rules and portable-records section.

Run `python scripts/sync.py` after editing either source; `--check` exits 1 if anything is stale.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SKILLS = {'en': 'skills/study-companion', 'zh': 'skills/study-companion-zh'}
STARTER_LIMIT = 6000  # characters; a starter prompt has to fit in one paste

HEADER = {
    'en': """# Study Companion starter prompt

<!-- Generated by scripts/sync.py from the skill. Edit the skill, not this file. -->

Paste everything below the line into your AI assistant: as project instructions if it has projects, otherwise as the first message of a new chat. Then attach or paste your latest `handoff.md` if you have one.

---

You are my study companion. Teach me a course from my own materials and keep records that separate what I asked, what you explained, and what I showed I can do. Reply in my language and keep technical terms in the language of the course. If you can run commands and have the study-companion skill installed, use it instead of this prompt.
""",
    'zh': """# 学习伙伴启动提示词

<!-- 由 scripts/sync.py 根据 Skill 生成。请修改 Skill，不要直接改本文件。 -->

把分隔线以下的全部内容粘贴给你的 AI 助手：有项目功能就放进项目指令，没有就作为新对话的第一条消息。如果已有最新的 `handoff.md`，随后上传或粘贴它。

---

你是我的学习伙伴。请依据我自己的课程资料教我，并留下能分清"我问过什么、你讲过什么、我证明自己会什么"的记录。默认用中文讲解，专业术语保留课程所用的语言。如果你能运行命令并且已安装 study-companion-zh Skill，请使用它而不是本提示词。
""",
}
RECORDS = {'en': '## Keeping records without tools\n', 'zh': '## 没有工具时如何记录\n'}


def section(path: Path, name: str) -> str:
    match = re.search(rf'<!-- {name}:start -->\n(.*?)<!-- {name}:end -->', path.read_text(encoding='utf-8'), re.S)
    if not match:
        raise ValueError(f'{path} has no {name} section.')
    return match.group(1).strip()


def starter(root: Path, language: str) -> str:
    skill = root / SKILLS[language]
    rules = section(skill / 'SKILL.md', 'core-rules')
    records = section(skill / 'references/portable.md', 'portable').replace('\n## ', '\n### ')
    records = re.sub(r'^## ', '### ', records)
    return '\n'.join([HEADER[language], rules, '', RECORDS[language], records, ''])


def script_files(root: Path, language: str) -> dict[str, bytes]:
    base = root / SKILLS[language] / 'scripts'
    return {p.relative_to(base).as_posix(): p.read_bytes() for p in sorted(base.rglob('*.py'))}


def stale(root: Path = ROOT) -> list[str]:
    """Names of derived files that differ from what their sources produce."""
    problems = []
    if script_files(root, 'en') != script_files(root, 'zh'):
        problems.append(f"{SKILLS['zh']}/scripts")
    for language in SKILLS:
        target = root / f'templates/starter-prompt.{language}.md'
        text = starter(root, language)
        if len(text) > STARTER_LIMIT:
            raise ValueError(f'{target.name} is {len(text)} characters; the limit is {STARTER_LIMIT}.')
        if not target.exists() or target.read_text(encoding='utf-8') != text:
            problems.append(target.relative_to(root).as_posix())
    return problems


def write(root: Path = ROOT) -> None:
    target = root / SKILLS['zh'] / 'scripts'
    wanted = script_files(root, 'en')
    for path in list(target.rglob('*.py')) if target.exists() else []:
        if path.relative_to(target).as_posix() not in wanted:
            path.unlink()
    for name, data in wanted.items():
        (target / name).parent.mkdir(parents=True, exist_ok=True)
        (target / name).write_bytes(data)
    for language in SKILLS:
        (root / f'templates/starter-prompt.{language}.md').write_text(starter(root, language), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    cli = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    cli.add_argument('--check', action='store_true')
    if cli.parse_args().check:
        problems = stale()
        print('\n'.join(f'stale: {p}' for p in problems) or 'up to date')
        sys.exit(1 if problems else 0)
    write()
    print('synced')
