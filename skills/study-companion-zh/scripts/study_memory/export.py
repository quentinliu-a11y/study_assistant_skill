def short(event_id: str) -> str:
    """Event ids are a 64-character batch hash plus an index; show eight characters in Markdown."""
    batch, _, index = event_id.rpartition(':')
    return f'{batch[:8]}:{index}'


def event_lines(event: dict, t: dict, from_digest: bool = False) -> list[str]:
    lines = [f"### {', '.join(event['concept_ids'])}", '', t['question'].format(event['question']),
             t['explanation'].format(event['explanation_status']), t['mastery_line'].format(t['mastery'][event['mastery']]),
             t['links'].format(', '.join(event['links']) or t['no_links']), t['event'].format(short(event['event_id']))]
    if event['correction_of']:
        lines.append(t['corrects'].format(short(event['correction_of'])))
    for evidence in event['mastery_evidence']:
        lines.append(t['evidence'].format(' / '.join(evidence['source_turn_id']), evidence['quote']))
    if not event['mastery_evidence']:
        lines.append(t['no_evidence'])
    if from_digest:
        lines.append(t['from_digest'])
    return lines


def export_course(db_path: Path, course_id: str, output_dir: Path, timezone: str, language: str = 'zh') -> list[Path]:
    safe_course_id(course_id)
    if language not in TEXT:
        raise ValueError('language must be en or zh.')
    zone = zone_of(timezone)
    output_dir = Path(output_dir).resolve()
    base = (output_dir / course_id).resolve()
    if not base.is_relative_to(output_dir):
        raise ValueError('Course directory escapes output directory.')
    base.mkdir(parents=True, exist_ok=True)
    lock_path = checked_path(base, '.export-lock.sqlite3')
    # A separate SQLite file serializes exporters without blocking study commits.
    lock = sqlite3.connect(lock_path, timeout=30)
    try:
        lock.execute('BEGIN IMMEDIATE')
        return export_locked(db_path, course_id, base, timezone, zone, TEXT[language])
    finally:
        lock.rollback()
        lock.close()


def checked_path(base: Path, relative: str) -> Path:
    path = base / relative
    if not path.resolve().is_relative_to(base):
        raise ValueError('Export path escapes course directory.')
    return path


def review_files(db_path, course_id, t) -> tuple[dict, list[dict]]:
    """Markdown for the question list and review history; empty when no question was ever recorded."""
    questions = list_questions(db_path, course_id)
    if not questions:
        return {}, []
    lines = [MARKER, t['questions_title'].format(course_id), '']
    for q in questions:
        lines += [f"## {q['question_id']}", '', t['confusion'].format(q['confusion']), t['prompt'].format(q['prompt']),
                  t['status'].format(t['mastery'][q['status']], t['is_recurring'] if q['recurring'] else t['single'],
                                     len({o['source'] for o in q['occurrences']}))]
        if q['concept_ids']:
            lines.append(t['concepts'].format(', '.join(q['concept_ids'])))
        lines += [t['occurrence'].format(o['date'], o['source'], f" · {o['note']}" if o['note'] else '') for o in q['occurrences']]
        lines += [t['schedule'].format(q['streak'], q['due'] or t['any_time']),
                  t['last_review'].format(q['last_reviewed'] or t['none']), '']
    history, day = [MARKER, t['history_title'].format(course_id), ''], None
    for row in review_history(db_path, course_id):
        if row['day'] != day:
            day = row['day']
            history += ([''] if len(history) > 3 else []) + [f'## {day}', '']
        history.append(t['day_skipped'] if row['question_id'] == DAY_SKIP else t['review_line'].format(
            row['question_id'], t['outcome'][row['outcome']], f" · {row['note']}" if row['note'] else ''))
    return {MANAGED[0]: '\n'.join(lines).rstrip() + '\n', MANAGED[1]: '\n'.join(history).rstrip() + '\n'}, questions


def export_locked(db_path, course_id, base, timezone, zone, t):
    state = read_course(db_path, course_id)
    turns = {turn_key(turn): turn for turn in state['turns']}
    # A correction replaces the event it corrects in the current state; both stay in the daily logs.
    superseded = {e['correction_of'] for batch in state['updates'] for e in batch['update']['events'] if e['correction_of']}
    days, latest = defaultdict(list), {}
    next_start, newest = t['no_records'], ''
    for batch in state['updates']:
        update = batch['update']
        batch_latest = ''
        for event in update['events']:
            refs = [turns[tuple(r)] for r in event['source_turn_ids']]
            from_digest = any(turn.get('source_kind') == 'digest' for turn in refs)
            event_time = max(turn['occurred_at'] for turn in refs)
            batch_latest = max(batch_latest, event_time)
            for concept in event['concept_ids']:
                old = latest.get(concept)
                if event['event_id'] not in superseded and (old is None or event_time >= old[0]):
                    latest[concept] = (event_time, event, from_digest)
            by_day = defaultdict(list)
            for turn in refs:
                by_day[parse_time(turn['occurred_at']).astimezone(zone).date().isoformat()].append(turn)
            for day, day_turns in by_day.items():
                lines = event_lines(event, t, from_digest) + ['', t['processed'].format(batch['created_at'], batch['version']), '']
                for turn in sorted(day_turns, key=lambda turn: (turn['occurred_at'], turn['turn_id'])):
                    lines.append(t['source'].format(turn['thread_id'], turn['turn_id'],
                                                    parse_time(turn['occurred_at']).astimezone(zone).isoformat()))
                lines.extend(['', t['batch_next'].format(update['next_start']), ''])
                days[day].append((min(turn['occurred_at'] for turn in day_turns), event['event_id'], lines))
        if batch_latest >= newest:
            newest, next_start = batch_latest, update['next_start']
    header = [t['state_title'].format(course_id), '', t['version_zone'].format(state['version'], timezone),
              t['latest'].format(newest or t['none']), '', t['next_heading'], '', next_start, '', t['concepts_heading'], '']
    active = {}
    for concept, (timestamp, event, from_digest) in latest.items():
        if event['event_id'] not in active:
            active[event['event_id']] = (timestamp, dict(event, concept_ids=[]), from_digest)
        active[event['event_id']][1]['concept_ids'].append(concept)
    current = sorted(active.values(), key=lambda item: (item[0], item[1]['event_id']))
    for _, event, from_digest in current:
        header.extend(event_lines(event, t, from_digest) + ['', t['source_turns'].format(
            '; '.join(' / '.join(r) for r in event['source_turn_ids'])), ''])
    rendered = {}
    for day, sections in sorted(days.items()):
        lines = [t['log_title'].format(course_id, day), '', t['log_note'].format(state['version'], timezone), '']
        for _, _, section in sorted(sections):
            lines.extend(section)
        rendered[f'logs/{day}.md'] = '\n'.join(lines) + '\n'
    extra, questions = review_files(db_path, course_id, t)
    handoff = [t['handoff_title'].format(course_id), '', t['handoff_note'].format(state['version']), '',
               t['next_heading'], '', next_start, '', t['open_concepts'], '']
    weak = [f"- {', '.join(e['concept_ids'])}: {e['question']} ({t['mastery'][e['mastery']]})"
            for _, e, _ in current if e['mastery'] in ('unverified', 'needs_help')]
    review_days = [row['day'] for row in review_history(db_path, course_id)]
    handoff += (weak or [t['nothing']]) + ['', t['open_questions'], '', t['last_day'].format(max(review_days, default=t['none'])), '']
    handoff += [t['handoff_question'].format(q['question_id'], t['mastery'][q['status']], q['due'] or t['any_time'], q['prompt'])
                for q in questions] or [t['nothing']]
    manifest_path = checked_path(base, '.export-manifest.json')
    old = json.loads(manifest_path.read_text(encoding='utf-8')) if manifest_path.exists() else {}
    if not isinstance(old, dict):
        raise ValueError('Invalid export manifest.')
    for name, hashes in old.items():
        if not re.fullmatch(r'logs/\d{4}-\d{2}-\d{2}\.md', name) or not isinstance(hashes, list):
            raise ValueError('Invalid export manifest entry.')
        path = checked_path(base, name)
        if name not in rendered and path.exists() and hashlib.sha256(path.read_bytes()).hexdigest() not in hashes:
            raise ValueError(f'Obsolete generated log was edited; move your notes before retrying: {name}')
    desired = {name: [hashlib.sha256(content.encode('utf-8')).hexdigest()] for name, content in rendered.items()}
    # Journal both generations before writing, so an interrupted export is retryable.
    pending = {name: list(hashes) for name, hashes in old.items()}
    for name, hashes in desired.items():
        pending[name] = sorted(set(pending.get(name, []) + hashes))
    atomic_text(manifest_path, json.dumps(pending, sort_keys=True) + '\n')
    paths = []
    for name, content in rendered.items():
        path = checked_path(base, name)
        atomic_text(path, content)
        paths.append(path)
    for name in old.keys() - desired.keys():
        path = checked_path(base, name)
        if path.exists():
            path.unlink()
    for name, content in extra.items():
        path = checked_path(base, name)
        # A hand-kept list from before 0.2 is set aside once, never overwritten.
        if path.exists() and not path.read_text(encoding='utf-8').startswith(MARKER):
            backup = checked_path(base, name.replace('.md', '.manual-backup.md'))
            if backup.exists():
                raise ValueError(f'Move your hand-written {name} away before exporting; a backup already exists.')
            path.replace(backup)
        atomic_text(path, content)
        paths.append(path)
    path = checked_path(base, 'handoff.md')
    atomic_text(path, '\n'.join(handoff) + '\n')
    paths.append(path)
    path = checked_path(base, 'current-state.md')
    # Publish current-state last. If any other file fails, retry the whole export.
    atomic_text(path, '\n'.join(header) + '\n')
    paths.append(path)
    atomic_text(manifest_path, json.dumps(desired, sort_keys=True) + '\n')
    return paths
